"""Build web/js/taller_data.js from the machine table extracted from
70/BD7000.PAG (taller_machines.json, see docs/TALLER_RULES.md).

usage: python gen_taller_data.py taller_machines.json ../web/js/taller_data.js
"""
import json
import sys

# Constants read from the BD7000 listing (see TALLER_RULES.md 5.3 / 5.5 / 2.5).
FLOOR_X = [-40, 138, -114, -141, 209, 103, -142, 33, 37, 68, -85, 155, -77, 157, 113, 12, 81,
           -50, -83, 138, -50, 75, -180, -10, -48, -75, -220, -3, -4, 238, -173, 40, 52, 52, 52]
FAIL_FX = [[336, 218], [374, 181], [316, 144], [290, 186], [265, 194]]
HELP = [
    "A1. Pulsa el botón en la parte superior de la pantalla para construir una máquina. "
    "Ahora pulsa uno de los nombres para empezar.",
    "A2. El diagrama dispone de dos pasos:\n\n1. Selecciona las piezas para la máquina a partir de "
    "las imágenes cuadradas.\n\n2. Verifica el funcionamiento conjunto de las piezas usando las "
    "imágenes circulares.",
    "A3. Arrastra las imágenes a los espacios donde desees colocarlas para completar el diagrama. "
    "Si cambias de opinión, arrástralas a otro lugar. Usa las flechas de la parte inferior de la "
    "pantalla para ver todas las piezas.",
    "A4. Las imágenes circulares sirven para conectar las piezas. Lee el nombre y la descripción en "
    "la parte superior de la ventana de cada una de las imágenes. El flujo de las líneas del "
    "diagrama indican el tipo de conexión.",
    "A5. Cuando hayas terminado, pulsa el botón Construir. No olvides rellenar todos los espacios "
    "en blanco.",
]


def main(src_path, out_path):
    src = json.load(open(src_path, encoding="utf-8"))
    machines = []
    for m in src["machines"]:
        anim = m.get("anim")
        machines.append({
            "id": m["id"], "name": m["name"], "intro": m.get("intro"), "fail": m.get("fail"),
            "powerPos": m["powerPos"], "partsPage": m["partsPage"], "partsGfx": m["partsGfx"],
            "anim": int(str(anim).replace("BD", "")) if anim else None,
            "animFrames": m.get("animFrames"), "cues": m.get("cues", []),
            "components": [{"pos": c["pos"], "x": c["iconX"], "y": c["iconY"], "id": c["id"]}
                           for c in m["components"]],
            "links": [{"idx": l["idx"], "x": l["iconX"], "y": l["iconY"], "type": l["type"]}
                      for l in m["links"]],
            "given": [{"kind": g["kind"], "row": g["row"], "col": g["col"], "value": g["value"]}
                      for g in m["given"]],
        })
    out = {
        "components": src["components"][:32],
        "connections": src["connections"],
        "machines": machines,
        "floorX": FLOOR_X,
        "failFx": FAIL_FX,
        "help": HELP,
    }
    js = ("// Machine workshop (section 70) data, extracted from 70/BD7000.PAG.\n"
          "// See docs/TALLER_RULES.md. Generated by tools/gen_taller_data.py.\n"
          "'use strict';\n\nconst TALLER = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(js)
    for m in machines:
        print(m["id"], m["name"], m["anim"], m["animFrames"], len(m["components"]), len(m["links"]), m["given"])


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
